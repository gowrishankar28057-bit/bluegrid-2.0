import { expect, test } from '@playwright/test'

test('renders real WebGL, supports drag/zoom/grid and geographical selection', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.globe-renderer')).toHaveAttribute('data-ready', 'true')
  const canvas = page.locator('canvas')
  await expect(canvas).toBeVisible()
  await page.getByRole('button', { name: 'Pause globe rotation' }).click()
  await expect(page.getByRole('button', { name: 'Start globe rotation' })).toBeVisible()
  const before = await canvas.screenshot()
  const bounds = await canvas.boundingBox()
  if (!bounds) throw new Error('Canvas bounds missing')
  await page.mouse.move(bounds.x + bounds.width * .5, bounds.y + bounds.height * .5)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width * .65, bounds.y + bounds.height * .53, { steps: 15 })
  await page.mouse.up()
  await expect.poll(async () => Buffer.compare(before, await canvas.screenshot())).not.toBe(0)
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await page.getByRole('button', { name: 'Geographic grid', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Geographic grid', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Reset globe view' }).click()
  await page.locator('.location-list').getByRole('button', { name: /Brest/ }).click()
  await expect(page.locator('.location-summary')).toContainText('Brest, France')
  await expect(page.locator('.coordinate-readout')).toContainText('4.49° W')
  await page.getByLabel('Search demonstration locations').fill('India')
  await expect(page.locator('.location-option')).toHaveCount(1)
  await page.getByLabel('Search demonstration locations').press('Enter')
  await expect(page.locator('.location-summary')).toContainText('Lakshadweep, India')
  expect(errors).toEqual([])
})

test('opens a planning form and handles an actual backend response', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start planning', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('Electricity demand (kW)')).toBeFocused()
  await page.getByRole('button', { name: 'Evaluate configuration' }).click()
  await expect(page.locator('.planning-result')).toBeVisible({ timeout: 25000 })
  await expect(page.locator('.planning-result')).toContainText('Annual energy served')
  await expect(page.locator('.planning-error')).toHaveCount(0)
  await page.getByRole('button', { name: 'Close energy planner' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('mobile layout and keyboard/reduced-motion controls remain usable', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('.globe-renderer')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByRole('button', { name: 'Start globe rotation' })).toBeVisible()
  const stage = page.locator('.globe-stage')
  await stage.focus()
  await stage.press('ArrowLeft')
  await stage.press('+')
  await page.getByLabel('Search demonstration locations').fill('Nowhere')
  await expect(page.getByText(/No supported location found/)).toBeVisible()
  await page.getByRole('button', { name: 'Clear location search' }).click()
  await expect(page.locator('.location-option')).toHaveCount(2)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  await page.screenshot({ path: 'test-results/mobile-earth.png', fullPage: true })
})
